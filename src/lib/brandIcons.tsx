export function brandIconFor(url: string): BrandIconComponent | null {
  try {
    const hostname = new URL(url).hostname.replace(/^www\./, '')
    const match = DOMAIN_ICONS.find(([domain]) => hostname.includes(domain))
    return match ? match[1] : null
  } catch {
    return null
  }
}
