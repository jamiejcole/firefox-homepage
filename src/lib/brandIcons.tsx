export type BrandIconComponent = (props: SVGProps<SVGSVGElement>) => ReactNode

/** Wraps a simple-icons path string as a component with the same shape as a react-icons icon. */
function fromPath(path: string): BrandIconComponent {
  return (props) => (
    <svg role="img" viewBox="0 0 24 24" fill="currentColor" aria-hidden {...props}>
      <path d={path} />
    </svg>
  )
}

